-- 0007_lid_open_ms.sql
-- เก็บระยะเวลาเปิดฝาเป็นมิลลิวินาทีตามที่บอร์ดวัดได้จริง
--
-- คอลัมน์เดิมเป็นวินาทีแบบจำนวนเต็ม ทำให้เกิดปัญหาสองอย่าง
--   1. การเปิดฝา 1.9 วินาทีถูกปัดเป็น 1 แล้วถูกคัดทิ้งว่าเป็นการเปิดที่สั้นเกินไป
--      ทั้งที่เป็นการหยิบยาจริง ในการทดสอบ 100 ครั้งพบว่าหายไปราวครึ่งหนึ่ง
--   2. ความละเอียดระดับวินาทีหยาบเกินกว่าจะรายงานค่าเฉลี่ยและส่วนเบี่ยงเบนได้
--
-- คอลัมน์เดิมยังอยู่ เพื่อให้ข้อมูลที่เก็บไว้ก่อนหน้านี้ยังอ่านได้เหมือนเดิม
alter table public.logs          add column if not exists lid_open_ms int;
alter table public.device_events add column if not exists lid_open_ms int;

-- เก็บขนาดไฟล์ภาพ ใช้คัดกรองภาพที่ถ่ายผิดจังหวะ
-- ภาพภายในกล่องที่ปิดฝาแล้วมีขนาดใกล้เคียงกันทุกใบ ภาพที่ใหญ่ผิดปกติหลายเท่า
-- มักเป็นภาพตอนฝายังเปิดซึ่งติดฉากหลังของห้องเข้ามาด้วย
alter table public.log_images add column if not exists bytes int;
